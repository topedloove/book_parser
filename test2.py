def translater():
	hide_text = text.get('1.0', END)
	translate = []
	for char in hide_text:
		if char not in eng_to_rus_decrypt:
			continue
		else:
			translate.append(eng_to_rus_decrypt[char])
	result = ''.join(translate)
	text1.delete('1.0', END)
	text1.insert('1.0', result)



